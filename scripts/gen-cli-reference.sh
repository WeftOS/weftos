#!/usr/bin/env bash
# Generate the weaver / weft CLI reference from the built binaries' `--help`.
#
# Walks every subcommand recursively (subcommands sorted alphabetically), and
# writes one fenced help block per command. Output is deterministic: no
# timestamps, no version strings, and the home directory is rewritten to `~`.
#
# Usage:
#   scripts/gen-cli-reference.sh [--weaver PATH] [--weft PATH] [--check]
#   scripts/build.sh gen-cli-reference        # build native-debug, then generate
#   scripts/build.sh check-cli-reference      # build native-debug, then --check
#
# Defaults: target/debug/weaver and target/debug/weft (scripts/build.sh native-debug).
# --check regenerates into a temp dir and fails (exit 1) if any tracked output
# differs, instead of overwriting it. CI uses this to catch help-text drift.
#
# Outputs:
#   docs/reference/cli.md                                        both binaries, plain Markdown
#   docs/src/content/docs/clawft/cli-reference-weaver.mdx        site page
#   docs/src/content/docs/clawft/cli-reference-weft.mdx          site page
set -uo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
ROOT="$(cd "$SCRIPT_DIR/.." && pwd)"
cd "$ROOT"

WEAVER="target/debug/weaver"
WEFT="target/debug/weft"
CHECK=false
while [ $# -gt 0 ]; do
    case "$1" in
        --weaver) WEAVER="${2:?--weaver needs a path}"; shift 2 ;;
        --weft) WEFT="${2:?--weft needs a path}"; shift 2 ;;
        --check) CHECK=true; shift ;;
        -h|--help) sed -n '2,21p' "$0"; exit 0 ;;
        *) echo "unknown argument: $1" >&2; exit 2 ;;
    esac
done

for b in "$WEAVER" "$WEFT"; do
    [ -x "$b" ] || { echo "missing binary: $b (run scripts/build.sh native-debug)" >&2; exit 2; }
done

OUT_MD="docs/reference/cli.md"
OUT_WEAVER="docs/src/content/docs/clawft/cli-reference-weaver.mdx"
OUT_WEFT="docs/src/content/docs/clawft/cli-reference-weft.mdx"

WORK="$(mktemp -d "${TMPDIR:-/tmp}/gen-cli-ref.XXXXXX")"
trap 'rm -rf "$WORK"' EXIT

# Run `--help`, normalise host-specific text. NO_COLOR keeps clap plain.
help_of() { # binary args...
    local bin="$1"; shift
    NO_COLOR=1 COLUMNS=100 "$bin" "$@" --help 2>&1 </dev/null \
        | sed -e "s#${HOME}#~#g" -e 's#/Users/[A-Za-z0-9._-]*#~#g' -e 's#/home/[A-Za-z0-9._-]*#~#g' \
        | sed -e 's/[[:space:]]*$//'
}

# Subcommand names from a help text's `Commands:` section, sorted, minus `help`.
subcommands() { # help-text on stdin
    awk '
        /^Commands:/ { on = 1; next }
        on && /^[^ ]/ { on = 0 }
        on && /^  [a-z0-9]/ { print $1 }
    ' | grep -vx 'help' | LC_ALL=C sort
}

# Emit the sections for one command and recurse. depth 2 = `##` for top level.
walk() { # outfile bin depth name...
    local out="$1" bin="$2" depth="$3"; shift 3
    local help hashes
    help="$(help_of "$bin" "${@:2}")"
    hashes="$(printf '%*s' "$depth" '' | tr ' ' '#')"
    {
        printf '%s `%s`\n\n```text\n%s\n```\n\n' "$hashes" "$*" "$help"
    } >> "$out"
    local sub
    while IFS= read -r sub; do
        [ -n "$sub" ] || continue
        walk "$out" "$bin" $((depth < 6 ? depth + 1 : 6)) "$@" "$sub"
    done < <(printf '%s\n' "$help" | subcommands)
}

body() { # outfile bin name
    local out="$1" bin="$2" name="$3"
    : > "$out"
    local top
    top="$(help_of "$bin")"
    {
        printf '%s\n\n' "Generated by \`scripts/gen-cli-reference.sh\` from \`$name --help\`. Do not edit by hand; run \`scripts/build.sh gen-cli-reference\`."
        printf '## Commands\n\n'
        printf '%s\n' "$top" | subcommands | while IFS= read -r c; do
            [ -n "$c" ] && printf -- '- [`%s %s`](#%s-%s)\n' "$name" "$c" "$name" "$c"
        done
        printf '\n'
    } >> "$out"
    walk "$out" "$bin" 2 "$name"
}

gen() { # destdir
    local d="$1"
    mkdir -p "$d"
    body "$d/weaver.body" "$WEAVER" weaver
    body "$d/weft.body" "$WEFT" weft
    {
        printf '# CLI reference\n\n'
        printf '# weaver\n\n'; sed 's/^## /## /' "$d/weaver.body"
        printf '\n# weft\n\n'; cat "$d/weft.body"
    } > "$d/cli.md"
    for n in weaver weft; do
        {
            printf -- '---\ntitle: "CLI Reference: %s"\n' "$n"
            printf 'description: "Generated reference for every %s command and subcommand, taken from the built binary."\n---\n\n' "$n"
            cat "$d/$n.body"
        } > "$d/$n.mdx"
    done
}

# Leak check: generated output must not carry a home path or hostname.
leak_check() { # dir
    if grep -nE '/Users/|/home/|/Volumes/|\.local\b|\.lan\b' "$1/cli.md" "$1/weaver.mdx" "$1/weft.mdx" >&2; then
        echo "leak check failed: host-specific text in generated output" >&2
        return 1
    fi
}

gen "$WORK/out" || exit 1
leak_check "$WORK/out" || exit 1

if [ "$CHECK" = true ]; then
    rc=0
    for pair in "cli.md:$OUT_MD" "weaver.mdx:$OUT_WEAVER" "weft.mdx:$OUT_WEFT"; do
        src="$WORK/out/${pair%%:*}"; dst="${pair#*:}"
        if ! diff -u "$dst" "$src" > "$WORK/diff.txt" 2>&1; then
            echo "DRIFT: $dst differs from the built binaries" >&2
            head -40 "$WORK/diff.txt" >&2
            rc=1
        fi
    done
    [ "$rc" -eq 0 ] && echo "cli reference up to date"
    exit "$rc"
fi

cp "$WORK/out/cli.md" "$OUT_MD"
cp "$WORK/out/weaver.mdx" "$OUT_WEAVER"
cp "$WORK/out/weft.mdx" "$OUT_WEFT"
echo "wrote $OUT_MD $OUT_WEAVER $OUT_WEFT"
