//! `weft tapestry plugin --out <dir>`: materialise a Tapestry plugin directory
//! from the agent directory (R6 step 1, docs/grok-build-fork/plan.md).
//!
//! Layout written under `<dir>` (the format `tapestry --plugin-dir <dir>` loads):
//!
//! ```text
//! plugin.json          {"name":"weftos","agents":"./agents","mcpServers":"./.mcp.json"}
//! .mcp.json            one MCP server: `weft mcp-server --profile control`
//! agents/<id>.md       one per declared agent (persona + provenance), plus one
//!                      stub per running agent that has no declared package
//! ```
//!
//! Declared agents come from `agents/<id>/` packages through
//! `weftos::init::source::AgentSource` (never `catalog.json`). Output is a pure
//! function of the package tree and the set of running agent ids, so a re-run
//! is byte-identical. Only files this command generated are ever removed, and
//! only inside `<dir>/agents/`; a generated file carries [`MARKER`].

use std::collections::{BTreeMap, BTreeSet};
use std::path::{Path, PathBuf};

use clap::{Args, Subcommand};
use serde_json::{Value, json};
use weftos::init::package::Package;
use weftos::init::source::AgentSource;

use super::agent_directory::{locate_agents_dir, uri_for};

/// Plugin name; Tapestry qualifies agents as `weftos:<id>`.
pub const PLUGIN_NAME: &str = "weftos";
/// First body line of every generated agent file; the only files cleanup may delete.
pub const MARKER: &str = "<!-- generated by `weft tapestry plugin`; edits are overwritten -->";

/// Arguments for `weft tapestry`.
#[derive(Args)]
pub struct TapestryArgs {
    #[command(subcommand)]
    pub action: TapestryAction,
}

/// Subcommands for `weft tapestry`.
#[derive(Subcommand)]
pub enum TapestryAction {
    /// Write a Tapestry plugin directory surfacing WeftOS agents.
    Plugin(PluginArgs),
}

/// Arguments for `weft tapestry plugin`.
#[derive(Args)]
pub struct PluginArgs {
    /// Directory to write the plugin into (created if missing).
    #[arg(long, value_name = "DIR")]
    pub out: PathBuf,

    /// Agent package tree (overrides $WEFTOS_AGENTS_DIR and checkout discovery).
    #[arg(long, value_name = "DIR")]
    pub agents_dir: Option<PathBuf>,

    /// Do not ask the daemon for running agents.
    #[arg(long)]
    pub no_running: bool,

    /// Command the MCP entry runs.
    #[arg(long, default_value = "weft", value_name = "CMD")]
    pub weft_bin: String,

    /// Add `--attach` so the MCP server talks to the live daemon (fails at
    /// startup when none runs).
    #[arg(long)]
    pub attach: bool,
}

/// One agent to write.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct AgentFile {
    pub file_stem: String,
    pub content: String,
}

/// Replace characters outside `[A-Za-z0-9._-]` so ids are safe as names and paths.
pub fn safe(id: &str) -> String {
    id.chars()
        .map(|c| if c.is_ascii_alphanumeric() || matches!(c, '.' | '_' | '-') { c } else { '_' })
        .collect()
}

fn frontmatter(name: &str, description: &str) -> String {
    let mut m = serde_yaml::Mapping::new();
    m.insert("name".into(), name.into());
    let d = description.split_whitespace().collect::<Vec<_>>().join(" ");
    m.insert("description".into(), d.into());
    let y = serde_yaml::to_string(&m).unwrap_or_default();
    format!("---\n{y}---\n")
}

/// Declared agent file from a loaded package. `None` when the package has no persona.
pub fn declared_file(pkg: &Package, team_lines: &[String], state: &str, trust: Option<&str>) -> Option<AgentFile> {
    let p = pkg.persona.as_ref()?;
    let name = safe(&pkg.id);
    let mut out = frontmatter(&name, &p.description);
    out.push_str(MARKER);
    out.push_str("\n\n");
    out.push_str(p.body.trim_end());
    out.push_str("\n\n## WeftOS provenance\n\n");
    out.push_str(&format!(
        "- Declared agent `{}` (package `agents/{}`, kind `{}`, state `{}`{}).\n",
        uri_for(&pkg.id),
        pkg.id,
        if pkg.kind.is_empty() { "unknown" } else { &pkg.kind },
        state,
        trust.map(|t| format!(", trust tier `{t}`")).unwrap_or_default(),
    ));
    for l in team_lines {
        out.push_str(&format!("- {l}\n"));
    }
    if !p.tools.is_empty() {
        out.push_str(&format!(
            "- Declared tools (not applied here; Tapestry does not read them from this plugin): {}.\n",
            p.tools.join(", ")
        ));
    }
    out.push_str("- Model hints, authority, `must_not` and similar package fields are declared data, not enforced by this plugin.\n");
    Some(AgentFile { file_stem: name, content: out })
}

/// Stub for a running agent with no declared package.
pub fn running_only_file(id: &str) -> AgentFile {
    let name = safe(id);
    let mut out = frontmatter(&name, &format!("WeftOS agent `{id}` running on this node. No declared package: no persona available."));
    out.push_str(MARKER);
    out.push_str(&format!(
        "\n\nThis is a running WeftOS agent (`{}`) with no package in the agent tree, so no persona is known. \
         Use the `weftos` MCP tools (`agent_get`) to inspect it.\n",
        uri_for(id)
    ));
    AgentFile { file_stem: name, content: out }
}

/// `plugin.json` text.
pub fn manifest_json() -> String {
    let v = json!({
        "name": PLUGIN_NAME,
        "description": "WeftOS agents and control-plane MCP tools, generated by `weft tapestry plugin`.",
        "agents": "./agents",
        "mcpServers": "./.mcp.json",
    });
    format!("{}\n", serde_json::to_string_pretty(&v).unwrap_or_default())
}

/// `.mcp.json` text.
pub fn mcp_json(weft_bin: &str, attach: bool) -> String {
    let mut args = vec!["mcp-server", "--profile", "control"];
    if attach {
        args.push("--attach");
    }
    let v = json!({"mcpServers": {PLUGIN_NAME: {"command": weft_bin, "args": args}}});
    format!("{}\n", serde_json::to_string_pretty(&v).unwrap_or_default())
}

/// Result of planning: files keyed by path relative to the plugin dir.
pub struct Plan {
    pub files: BTreeMap<String, String>,
    pub skipped: Vec<String>,
}

/// Build the plan from a package tree and the running agent ids. Pure.
pub fn plan(src: &AgentSource, running: &BTreeSet<String>, weft_bin: &str, attach: bool) -> Result<Plan, String> {
    let teams = super::agent_directory::teams_of(src);
    let rows = super::agent_directory::rows_of(src, teams.as_ref().ok())?;
    let mut files = BTreeMap::new();
    let mut skipped = Vec::new();
    let mut declared_ids = BTreeSet::new();
    files.insert("plugin.json".to_string(), manifest_json());
    files.insert(".mcp.json".to_string(), mcp_json(weft_bin, attach));
    for r in &rows {
        let Some(id) = r["id"].as_str() else { continue };
        declared_ids.insert(id.to_string());
        let state = r["state"].as_str().unwrap_or("active");
        if state == "inactive" {
            skipped.push(format!("{id}: inactive"));
            continue;
        }
        let pkg = Package::load(src, id).map_err(|e| format!("{id}: {e}"))?;
        let mut tl = Vec::new();
        for m in r["teams"].as_array().into_iter().flatten() {
            let t = m["team"].as_str().unwrap_or("?");
            let lead = if m["lead"] == true { ", lead" } else { "" };
            tl.push(format!("Member of team `{t}`{lead}."));
        }
        match declared_file(&pkg, &tl, state, r["trust_tier"].as_str()) {
            Some(f) => {
                files.insert(format!("agents/{}.md", f.file_stem), f.content);
            }
            None => skipped.push(format!("{id}: no AGENT.md persona")),
        }
    }
    for id in running.difference(&declared_ids) {
        let f = running_only_file(id);
        files.insert(format!("agents/{}.md", f.file_stem), f.content);
    }
    Ok(Plan { files, skipped })
}

/// Write the plan under `dir`. Writes only changed files; removes stale
/// generated agent files (those carrying [`MARKER`]) inside `<dir>/agents/`.
/// Returns (written, removed) relative paths.
pub fn apply(dir: &Path, files: &BTreeMap<String, String>) -> Result<(Vec<String>, Vec<String>), String> {
    let ctx = |what: &str, p: &Path, e: std::io::Error| format!("{what} {}: {e}", p.display());
    std::fs::create_dir_all(dir.join("agents")).map_err(|e| ctx("create", dir, e))?;
    let mut written = Vec::new();
    for (rel, content) in files {
        let p = dir.join(rel);
        if std::fs::read_to_string(&p).ok().as_deref() == Some(content.as_str()) {
            continue;
        }
        std::fs::write(&p, content).map_err(|e| ctx("write", &p, e))?;
        written.push(rel.clone());
    }
    let mut removed = Vec::new();
    let rd = std::fs::read_dir(dir.join("agents")).map_err(|e| ctx("read", dir, e))?;
    for e in rd.flatten() {
        let p = e.path();
        let Some(name) = p.file_name().and_then(|n| n.to_str()).map(str::to_string) else { continue };
        let rel = format!("agents/{name}");
        if !p.is_file() || !name.ends_with(".md") || files.contains_key(&rel) {
            continue;
        }
        if std::fs::read_to_string(&p).map(|t| t.contains(MARKER)).unwrap_or(false) {
            std::fs::remove_file(&p).map_err(|e| ctx("remove", &p, e))?;
            removed.push(rel);
        }
    }
    written.sort();
    removed.sort();
    Ok((written, removed))
}

async fn running_ids() -> Result<BTreeSet<String>, String> {
    let Some(mut client) = super::daemon_conn::connect_opt().await else {
        return Err("no daemon reachable".into());
    };
    let resp = client.simple_call("agent.list").await.map_err(|e| e.to_string())?;
    let v: Value = resp.into_result().map_err(|e| e.to_string())?;
    let arr = v.as_array().ok_or_else(|| format!("agent.list returned {v}, expected an array"))?;
    Ok(arr.iter().filter_map(|r| r["agent_id"].as_str().map(str::to_string)).collect())
}

/// Run `weft tapestry`.
pub async fn run(args: TapestryArgs) -> anyhow::Result<()> {
    match args.action {
        TapestryAction::Plugin(a) => plugin(a).await,
    }
}

async fn plugin(a: PluginArgs) -> anyhow::Result<()> {
    let env_dir = a
        .agents_dir
        .as_ref()
        .map(|p| p.display().to_string())
        .or_else(|| std::env::var("WEFTOS_AGENTS_DIR").ok());
    let cwd = std::env::current_dir()?;
    let src = match locate_agents_dir(&cwd, env_dir.as_deref()).map_err(anyhow::Error::msg)? {
        Some(d) => AgentSource::from_dir(&d).map_err(|e| anyhow::anyhow!("{}: {e}", d.display()))?,
        None => AgentSource::embedded(),
    };
    let running = if a.no_running {
        BTreeSet::new()
    } else {
        match running_ids().await {
            Ok(s) => s,
            Err(e) => {
                eprintln!("note: running agents not included ({e}); declared agents only");
                BTreeSet::new()
            }
        }
    };
    let p = plan(&src, &running, &a.weft_bin, a.attach).map_err(anyhow::Error::msg)?;
    let (written, removed) = apply(&a.out, &p.files).map_err(anyhow::Error::msg)?;
    let agents = p.files.keys().filter(|k| k.starts_with("agents/")).count();
    println!("{} agents in {} ({} files written, {} stale removed)", agents, a.out.display(), written.len(), removed.len());
    for s in &p.skipped {
        println!("skipped {s}");
    }
    Ok(())
}

#[cfg(test)]
mod tests {
    use super::*;

    fn tree() -> tempfile::TempDir {
        let d = tempfile::tempdir().unwrap();
        let w = |rel: &str, t: &str| {
            let p = d.path().join(rel);
            std::fs::create_dir_all(p.parent().unwrap()).unwrap();
            std::fs::write(p, t).unwrap();
        };
        w("alpha/weftos-package.yaml", "name: alpha\nversion: 1.0.0\nkind: specialist\ntrust_tier: core\n");
        w(
            "alpha/AGENT.md",
            "---\nname: alpha\ndescription: >\n  Does the alpha job.\n  Use when: asked.\ntools: [Read, Grep]\n---\n\n# Alpha\n\nBe alpha.\n",
        );
        w("beta/weftos-package.yaml", "name: beta\nversion: 1.0.0\nkind: specialist\nstate: inactive\n");
        w("beta/AGENT.md", "---\nname: beta\ndescription: Beta.\n---\nBeta body.\n");
        w("docs-skill/weftos-package.yaml", "name: docs-skill\nversion: 1.0.0\nkind: skill\n");
        w("docs-skill/SKILL.md", "---\nname: docs-skill\ndescription: x\n---\nbody\n");
        w("agents-lane/weftos-package.yaml", "name: agents-lane\nversion: 1.0.0\nkind: lane\n");
        w("teams/crew/team.yaml", "name: crew\nlead: alpha\nmembers:\n  - agent: alpha\n");
        d
    }

    fn src(d: &tempfile::TempDir) -> AgentSource {
        AgentSource::from_dir(d.path()).unwrap()
    }

    #[test]
    fn golden_alpha() {
        let d = tree();
        let p = plan(&src(&d), &BTreeSet::new(), "weft", false).unwrap();
        let got = &p.files["agents/alpha.md"];
        let want = "---\nname: alpha\ndescription: 'Does the alpha job. Use when: asked.'\n---\n\
<!-- generated by `weft tapestry plugin`; edits are overwritten -->\n\n# Alpha\n\nBe alpha.\n\n\
## WeftOS provenance\n\n\
- Declared agent `weftos://agent/alpha` (package `agents/alpha`, kind `specialist`, state `active`, trust tier `core`).\n\
- Member of team `crew`, lead.\n\
- Declared tools (not applied here; Tapestry does not read them from this plugin): Read, Grep.\n\
- Model hints, authority, `must_not` and similar package fields are declared data, not enforced by this plugin.\n";
        assert_eq!(got, want);
    }

    #[test]
    fn inactive_and_non_agents_are_left_out_and_named() {
        let d = tree();
        let p = plan(&src(&d), &BTreeSet::new(), "weft", false).unwrap();
        assert!(p.files.contains_key("agents/alpha.md"));
        assert!(!p.files.contains_key("agents/beta.md"));
        assert!(!p.files.contains_key("agents/docs-skill.md"));
        assert!(p.skipped.iter().any(|s| s.starts_with("beta: inactive")));
        assert!(p.skipped.iter().any(|s| s.starts_with("agents-lane: no AGENT.md")));
    }

    #[test]
    fn running_only_agent_gets_a_stub_declared_one_does_not_duplicate() {
        let d = tree();
        let run: BTreeSet<String> = ["alpha", "ghost agent"].iter().map(|s| s.to_string()).collect();
        let p = plan(&src(&d), &run, "weft", false).unwrap();
        assert_eq!(p.files["agents/alpha.md"], plan(&src(&d), &BTreeSet::new(), "weft", false).unwrap().files["agents/alpha.md"]);
        let g = &p.files["agents/ghost_agent.md"];
        assert!(g.contains("name: ghost_agent") && g.contains("No declared package"));
    }

    #[test]
    fn mcp_and_manifest_shape() {
        let m: Value = serde_json::from_str(&mcp_json("weft", false)).unwrap();
        assert_eq!(m["mcpServers"]["weftos"]["args"], json!(["mcp-server", "--profile", "control"]));
        let m: Value = serde_json::from_str(&mcp_json("/x/weft", true)).unwrap();
        assert_eq!(m["mcpServers"]["weftos"]["command"], "/x/weft");
        assert_eq!(m["mcpServers"]["weftos"]["args"][3], "--attach");
        let p: Value = serde_json::from_str(&manifest_json()).unwrap();
        assert_eq!(p["agents"], "./agents");
    }

    #[test]
    fn apply_is_idempotent_and_removes_only_generated_files() {
        let d = tree();
        let out = tempfile::tempdir().unwrap();
        let outside = out.path().join("keep.txt");
        std::fs::write(&outside, "mine").unwrap();
        std::fs::create_dir_all(out.path().join("agents")).unwrap();
        std::fs::write(out.path().join("agents/handmade.md"), "---\nname: h\n---\nhand\n").unwrap();
        std::fs::write(out.path().join("agents/stale.md"), format!("---\nname: s\n---\n{MARKER}\n")).unwrap();

        let run: BTreeSet<String> = BTreeSet::new();
        let p = plan(&src(&d), &run, "weft", false).unwrap();
        let (w1, r1) = apply(out.path(), &p.files).unwrap();
        assert!(w1.contains(&"agents/alpha.md".to_string()));
        assert_eq!(r1, vec!["agents/stale.md".to_string()]);
        let (w2, r2) = apply(out.path(), &p.files).unwrap();
        assert!(w2.is_empty() && r2.is_empty(), "second run changes nothing: {w2:?} {r2:?}");
        assert!(out.path().join("agents/handmade.md").exists());
        assert_eq!(std::fs::read_to_string(outside).unwrap(), "mine");
    }

    #[test]
    fn empty_tree_refuses() {
        let d = tempfile::tempdir().unwrap();
        let s = AgentSource::from_dir(d.path());
        if let Ok(s) = s {
            assert!(plan(&s, &BTreeSet::new(), "weft", false).is_err());
        }
    }
}
